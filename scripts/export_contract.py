"""Generate the frontend's types and response schemas from Pydantic contracts."""

import json
from pathlib import Path

from backend.app.contracts import (
    EpisodeList,
    EpisodeView,
    Health,
    ModelStatus,
    PatientAssessment,
    Prediction,
    ResearchStatus,
    SystemInfo,
)

ROOT = Path(__file__).resolve().parents[1]
MODELS = (
    Health,
    SystemInfo,
    EpisodeList,
    EpisodeView,
    Prediction,
    ResearchStatus,
    PatientAssessment,
    ModelStatus,
)


def ts(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts(s) for s in schema["anyOf"])
    kind = schema.get("type")
    if kind == "object":
        if isinstance(schema.get("additionalProperties"), dict):
            return "Record<string, " + ts(schema["additionalProperties"]) + ">"
        required = schema.get("required", [])
        return (
            "{ "
            + "; ".join(
                f"{name}{'' if name in required else '?'}: {ts(value)}"
                for name, value in schema.get("properties", {}).items()
            )
            + " }"
        )
    if kind == "array":
        return f"Array<{ts(schema['items'])}>"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def main():
    schemas = {model.__name__: model.model_json_schema(mode="serialization") for model in MODELS}
    definitions = {}
    for schema in schemas.values():
        definitions.update(schema.get("$defs", {}))
    types = {**definitions, **schemas}
    result = "// Generated by python -m scripts.export_contract. Do not edit.\n"
    result += "\n".join(f"export type {name} = {ts(schema)};" for name, schema in types.items())
    result += "\nexport const contractSchemas = " + json.dumps(schemas, indent=2) + " as const;\n"
    (ROOT / "frontend/src/generated").mkdir(exist_ok=True)
    (ROOT / "frontend/src/generated/contracts.ts").write_text(result)
    from backend.app.episodes import EPISODES, episode_view

    fixtures = {
        "/api/v1/model/status": ModelStatus(
            state="not_configured",
            model_version=None,
            protocol_version=None,
            calibration=None,
            metrics=None,
            patient_import_enabled=False,
        ).model_dump(),
        "/api/v1/health": Health().model_dump(),
        "/api/v1/system/info": SystemInfo().model_dump(),
        "/api/v1/episodes": EpisodeList(
            episodes=[{"id": e.id, "name": e.name, "description": e.description} for e in EPISODES]
        ).model_dump(),
        "/api/v1/research/status": ResearchStatus().model_dump(),
    }
    for e in EPISODES:
        for hour in (0, 6, 14, 20, 32, 60, 72):
            view = EpisodeView.model_validate(episode_view(e, hour))
            fixtures[f"/api/v1/episodes/{e.id}?cutoff_hour={hour}"] = view.model_dump()
    (ROOT / "frontend/src/generated/test-fixtures.json").write_text(
        json.dumps(fixtures, indent=2) + "\n"
    )


if __name__ == "__main__":
    main()
